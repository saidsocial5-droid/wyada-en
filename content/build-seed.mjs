// Validates content/*/course.json and writes supabase/seed.sql.
// IDs are derived from the content path, so re-seeding updates rows in place.
// Run: node content/build-seed.mjs
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const uuid = (key) => { const h = createHash('md5').update(`wyada:${key}`).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-8${h.slice(17, 20)}-${h.slice(20, 32)}`; };
const q = (v) => v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`;
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;
const arr = (a) => `array[${a.map(q).join(',')}]::text[]`;
const words = (s) => s.toLowerCase().replace(/[^\p{L}\p{N}' ]/gu, ' ').split(/\s+/).filter(Boolean);
const KINDS = new Set(['multiple_choice', 'word_bank', 'translate_to_en']);

const errors = [];
const sql = ['-- generated by content/build-seed.mjs: do not edit', 'begin;'];
let count = 0;
for (const dir of readdirSync(here, { withFileTypes: true }).filter((d) => d.isDirectory())) {
  const file = join(here, dir.name, 'course.json');
  if (!existsSync(file)) continue;
  const c = JSON.parse(readFileSync(file, 'utf8'));
  const cid = uuid(c.slug);
  sql.push(`insert into courses (id, slug, from_language, title, published) values (${q(cid)}, ${q(c.slug)}, ${q(c.from_language)}, ${q(c.title)}, true)
  on conflict (id) do update set title = excluded.title, published = true;`);
  c.sections.forEach((s, si) => {
    const sid = uuid(`${c.slug}/s${si}`);
    sql.push(`insert into sections (id, course_id, position, title, cefr_level) values (${q(sid)}, ${q(cid)}, ${si + 1}, ${q(s.title)}, ${q(s.cefr)})
  on conflict (id) do update set title = excluded.title, cefr_level = excluded.cefr_level;`);
    s.units.forEach((u, ui) => {
      const uid = uuid(`${c.slug}/s${si}/u${ui}`);
      sql.push(`insert into units (id, section_id, position, title, colour, guidebook) values (${q(uid)}, ${q(sid)}, ${ui + 1}, ${q(u.title)}, ${q(`unit-${(ui % 6) + 1}`)}, ${j(u.guidebook ?? [])})
  on conflict (id) do update set title = excluded.title, guidebook = excluded.guidebook;`);
      u.nodes.forEach((n, ni) => {
        const nid = uuid(`${c.slug}/s${si}/u${ui}/n${ni}`);
        sql.push(`insert into path_nodes (id, unit_id, position, kind, levels) values (${q(nid)}, ${q(uid)}, ${ni + 1}, ${q(n.kind)}, ${n.levels ?? 1})
  on conflict (id) do update set kind = excluded.kind, levels = excluded.levels;`);
        const ids = [];
        n.exercises.forEach((e, ei) => {
          const at = `${c.slug} unit ${ui + 1} node ${ni + 1} exercise ${ei + 1}`;
          if (!KINDS.has(e.kind)) errors.push(`${at}: unknown kind ${e.kind}`);
          if (!e.solutions?.length) errors.push(`${at}: no solutions`);
          if (!e.prompt?.source) errors.push(`${at}: no prompt.source`);
          if (e.kind === 'multiple_choice' && !e.options?.includes(e.solutions[0])) errors.push(`${at}: first solution must be one of the options`);
          if (e.kind === 'word_bank') {
            const bank = (e.tokens ?? []).map((t) => t.toLowerCase());
            const need = words(e.solutions[0]);
            const left = [...bank];
            for (const w of need) { const i = left.indexOf(w); if (i < 0) errors.push(`${at}: word "${w}" missing from tokens`); else left.splice(i, 1); }
            if (left.length === 0) errors.push(`${at}: word bank needs at least one distractor`);
          }
          const eid = uuid(`${c.slug}/s${si}/u${ui}/n${ni}/e${ei}`);
          ids.push(eid);
          const prompt = { ...e.prompt, ...(e.options ? { options: e.options } : {}) };
          sql.push(`insert into exercises (id, node_id, level, position, kind, prompt, solutions, tokens) values (${q(eid)}, ${q(nid)}, ${e.level ?? 1}, ${ei + 1}, ${q(e.kind)}, ${j(prompt)}, ${arr(e.solutions)}, ${arr(e.tokens ?? [])})
  on conflict (id) do update set level = excluded.level, position = excluded.position, kind = excluded.kind, prompt = excluded.prompt, solutions = excluded.solutions, tokens = excluded.tokens;`);
          count++;
        });
        sql.push(`delete from exercises where node_id = ${q(nid)} and id not in (${ids.map(q).join(',')});`);
      });
    });
  });
}
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }
sql.push('commit;');
writeFileSync(join(here, '../supabase/seed.sql'), sql.join('\n') + '\n');
console.log(`seed.sql: ${count} exercises, 0 content errors`);
